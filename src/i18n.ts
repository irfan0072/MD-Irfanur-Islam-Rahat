const dict = { en, bn }
let cur: Lang = 'en'
export const setI18nLang = (l: Lang) => {
  cur = l
}

const BN_DIGITS = '০১২৩৪৫৬৭৮৯'
/** Numbers are shown in Bangla digits when the app is in Bangla. */
export function num(n: number | string): string {
  const s = String(n)
  return cur === 'bn' ? s.replace(/\d/g, (d) => BN_DIGITS[+d]) : s
}

export function tr(key: Key, vars?: Record<string, string | number>): string {
  let s = dict[cur][key] ?? en[key] ?? key
  // A name may appear more than once in a sentence, so every occurrence is filled in.
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(typeof vars[k] === 'number' ? num(vars[k]) : String(vars[k]))
  return s
}

export function fmtDate(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso)
  if (!m) return iso
  const d = new Date(+m[1], +m[2] - 1, +m[3])
  try {
    return new Intl.DateTimeFormat(cur === 'bn' ? 'bn-BD' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' }).format(d)
  } catch {
    return iso
  }
}

export function pagesLabel(n: number): string {
  return n === 1 ? tr('page1') : tr('pages', { n })
}
